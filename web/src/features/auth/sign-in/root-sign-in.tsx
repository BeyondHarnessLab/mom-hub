import { useTranslation } from 'react-i18next'

import { useStatus } from '@/hooks/use-status'

import { AuthLayout } from '../auth-layout'
import { TermsFooter } from '../components/terms-footer'
import { UserAuthForm } from './components/user-auth-form'

/**
 * Password sign-in for the root account. No page links here: it exists so root
 * can still sign in after the site turns password login off, which the server
 * allows for root alone.
 */
export function RootSignIn() {
  const { t } = useTranslation()
  const { status } = useStatus()

  return (
    <AuthLayout>
      <div className='w-full space-y-8'>
        <h2 className='text-center text-2xl font-semibold tracking-tight sm:text-left'>
          {t('Sign in')}
        </h2>

        <UserAuthForm passwordOnly />

        <TermsFooter
          variant='sign-in'
          status={status}
          className='text-center'
        />
      </div>
    </AuthLayout>
  )
}
